def _build_advice(
    grade: str, ac_count: int, coverage_count: int,
    test_case_count: int, cross_cutting_count: int,
    use_gherkin: bool, reverse_engineered: bool,
) -> str:
    gherkin_note = (
        " Gherkin E2E enabled for business-readable scenarios."
        if use_gherkin else " Gherkin off (dev-heavy team)."
    )
    re_note = (
        " ⚠ ACs were synthesised from the implementation — "
        "confirm with the PO before merge and re-run "
        "design_test_plan against the real ACs."
        if reverse_engineered else ""
    )
    return (
        f"Test plan grade: {grade}. {ac_count} ACs → {test_case_count} "
        f"planned test cases across {coverage_count} ACs. "
        f"{cross_cutting_count} cross-cutting concerns to cover "
        f"(a11y, l10n, lifecycle).{gherkin_note}{re_note}"
    )
